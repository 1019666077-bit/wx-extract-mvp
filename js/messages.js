function buildI18nScript(convert) {
  const hant = {};
  for (const [key, value] of Object.entries(MESSAGES)) {
    hant[key] = convert(value);
  }
  return `window.VOA_I18N=${JSON.stringify({ "zh-Hans": MESSAGES, "zh-Hant": hant })};\n`;
}

